from typing import List, Dict, Any, Optional
import math
import re
import hashlib
import numpy as np
from sqlalchemy.orm import Session
from app.models.knowledge import KnowledgeDocument, KnowledgeChunk
from app.core.config import settings

def simple_token_embed(text: str, dim: int = 64) -> List[float]:
    """
    Deterministic normalized vector embedding generator.
    Produces repeatable high-dimensional vectors for semantic cosine similarity
    without requiring external network downloads or API keys.
    """
    words = re.findall(r"\w+", text.lower())
    if not words:
        return [0.0] * dim
    
    vec = np.zeros(dim, dtype=float)
    for w in words:
        # Hash each word into vector buckets with sign
        digest = hashlib.sha256(w.encode("utf-8")).digest()
        h = int.from_bytes(digest[:8], byteorder="big")
        idx = h % dim
        sign = 1.0 if (h % 2 == 0) else -1.0
        vec[idx] += sign * (1.0 + math.log(1 + len(w)))
    
    norm = np.linalg.norm(vec)
    if norm > 0:
        vec = vec / norm
    return vec.tolist()

def cosine_similarity(v1: List[float], v2: List[float]) -> float:
    a = np.array(v1)
    b = np.array(v2)
    norm_a = np.linalg.norm(a)
    norm_b = np.linalg.norm(b)
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return float(np.dot(a, b) / (norm_a * norm_b))

class RAGEngine:
    """Multi-tenant RAG retrieval service with strict tenant isolation."""

    @staticmethod
    def index_document(db: Session, tenant_id: str, document_id: str, text: str):
        """Splits document text into chunks, generates embeddings, and saves to DB."""
        # Simple paragraph or sentence chunking
        paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
        if not paragraphs:
            paragraphs = [text.strip()]

        # Remove old chunks
        db.query(KnowledgeChunk).filter(
            KnowledgeChunk.document_id == document_id,
            KnowledgeChunk.tenant_id == tenant_id
        ).delete()

        chunks = []
        for idx, para in enumerate(paragraphs):
            embedding = simple_token_embed(para)
            chunk = KnowledgeChunk(
                id=f"chk-{document_id[:16]}-{idx}",
                tenant_id=tenant_id,
                document_id=document_id,
                chunk_index=idx,
                chunk_text=para,
                embedding=embedding,
                metadata_json={"chunk_index": idx}
            )
            chunks.append(chunk)
            db.add(chunk)
        db.commit()
        return chunks

    @staticmethod
    def search(
        db: Session,
        tenant_id: str,
        query: str,
        top_k: int = 3,
        min_score: float = 0.25
    ) -> List[Dict[str, Any]]:
        """
        Retrieves the top-k most relevant knowledge chunks strictly within the given tenant_id.
        """
        query_vec = simple_token_embed(query)
        
        # Strictly query only this tenant's chunks
        chunks = db.query(KnowledgeChunk).filter(
            KnowledgeChunk.tenant_id == tenant_id
        ).all()

        results = []
        for chunk in chunks:
            # Recompute from source text to avoid stale embeddings
            # generated by Python's process-dependent hash().
            chunk_vec = simple_token_embed(chunk.chunk_text)
            score = cosine_similarity(query_vec, chunk_vec)
            if score >= min_score:
                doc = db.query(KnowledgeDocument).filter(
                    KnowledgeDocument.id == chunk.document_id,
                    KnowledgeDocument.tenant_id == tenant_id
                ).first()
                
                results.append({
                    "chunk_id": chunk.id,
                    "document_id": chunk.document_id,
                    "document_title": doc.title if doc else "Policy Document",
                    "doc_type": doc.doc_type if doc else "POLICY",
                    "text": chunk.chunk_text,
                    "score": round(score, 3)
                })

        # Sort descending by similarity score
        results.sort(key=lambda x: x["score"], reverse=True)
        return results[:top_k]
